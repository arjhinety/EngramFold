"""Experiment definition freezes: has the definition changed since it was fixed?

An experiment manifest describes an intent. Once that intent is frozen -- before any
compute is spent -- the question that matters is whether it still says what it said. A
definition quietly edited after results are seen is the mechanism by which a
pre-registered rule becomes a rule chosen to fit the answer.

So an experiment freeze records the definition's identity at the moment it was fixed:

``definition_hash``
    The identity of the whole experiment manifest, volatile fields excluded.
``configuration_hash``
    The identity of the configuration block specifically, so a change to the parameters
    is distinguishable from a change to the surrounding prose.
``dataset_freezes``
    The frozen inputs that were pinned at freeze time.
``status_at_freeze``
    What the manifest claimed when it was frozen.
``code_revision_at_freeze``
    The code state when the freeze was taken.

Verification recomputes each of these against the manifest as it is now. Any disagreement
is reported as the specific field that moved, so "the definition changed" comes with
"here is what changed".

Same construction rules as dataset freezes
------------------------------------------

``freeze_id`` is computed over an explicitly listed set of identity fields, through the
same :func:`engramfold.hashing.selective_identity` the dataset freeze uses. The
timestamps and repository revision recorded alongside are provenance for the freeze
*event* and are excluded from the identity, so regenerating an unchanged freeze produces
the same id. :func:`write_experiment_freeze` refuses to replace a freeze whose identity
differs.
"""

from __future__ import annotations

from collections.abc import Mapping
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any

from engramfold.documents import load_document
from engramfold.errors import IntegrityError
from engramfold.experiments.manifest import (
    configuration_identity,
    experiment_identity,
)
from engramfold.hashing import pretty_json_text, selective_identity
from engramfold.schemas import current_version
from engramfold.validation.fields import (
    is_identifier,
    is_sha256,
    reject_unknown_fields,
    require_fields,
    require_int,
    validate_relative_posix_path,
)

IDENTITY_FIELDS: tuple[str, ...] = (
    "freeze_format_version",
    "experiment_id",
    "manifest_path",
    "definition_hash",
    "configuration_hash",
    "dataset_freezes",
    "status_at_freeze",
)

VOLATILE_FIELDS: tuple[str, ...] = (
    "freeze_id",
    "frozen_at",
    "repository_revision",
    "repository_dirty",
    "code_revision_at_freeze",
    "frozen_by_command",
    "generated_by",
)

TOP_LEVEL_FIELDS: tuple[str, ...] = IDENTITY_FIELDS + VOLATILE_FIELDS
REQUIRED_FIELDS: tuple[str, ...] = (*IDENTITY_FIELDS, "frozen_at", "generated_by")

#: A definition freeze is written by a tool, never by hand; the marker makes that legible.
GENERATED_BY_DEFAULT = "engramfold.experiments.freeze.build_experiment_freeze"

FREEZES_DIRECTORY = "experiments/freezes"
MANIFESTS_DIRECTORY = "experiments/manifests"


def freeze_format_version() -> int:
    """The freeze-format version this build writes."""
    return current_version("experiment_freeze")


@dataclass
class ExperimentFreezeResult:
    """What building an experiment freeze did."""

    freeze: dict[str, Any]
    output_path: str
    written: bool
    unchanged: bool
    byte_identical: bool = False
    errors: list[str] = field(default_factory=list)

    @property
    def ok(self) -> bool:
        return not self.errors


def experiment_freeze_identity(payload: Mapping[str, Any]) -> str:
    """The deterministic identity of an experiment freeze."""
    return selective_identity(payload, IDENTITY_FIELDS)


def freeze_relative_path(experiment_id: str) -> str:
    """Where the definition freeze for an experiment lives.

    Keyed by experiment id rather than by freeze id, because the question being asked is
    "what was this experiment's definition?" -- one answer per experiment. A second freeze
    for the same experiment is a rewrite of frozen history and is refused rather than
    filed alongside.
    """
    return f"{FREEZES_DIRECTORY}/{experiment_id}.json"


def build_experiment_freeze(
    manifest: Mapping[str, Any],
    manifest_path: str,
    *,
    frozen_at: str,
    repository_revision: str | None = None,
    repository_dirty: bool | None = None,
    code_revision_at_freeze: Mapping[str, Any] | None = None,
    frozen_by_command: str | None = None,
) -> ExperimentFreezeResult:
    """Construct a definition freeze for ``manifest``.

    ``frozen_at`` is required, not defaulted: a freeze whose timestamp the caller cannot
    supply cannot be regenerated byte-for-byte, and the idempotence guarantee depends on
    being able to.
    """
    errors: list[str] = []
    errors.extend(
        validate_relative_posix_path(
            manifest_path, origin="experiment freeze", label="manifest_path"
        )
    )
    experiment_id = manifest.get("experiment_id")
    if not is_identifier(experiment_id):
        errors.append(
            f"experiment freeze: manifest has no usable experiment_id, found {experiment_id!r}"
        )
    configuration = manifest.get("configuration")
    if not isinstance(configuration, dict):
        errors.append(
            "experiment freeze: manifest has no configuration block, so there is no definition "
            "to freeze"
        )
        configuration = {}

    payload: dict[str, Any] = {
        "freeze_format_version": freeze_format_version(),
        "experiment_id": experiment_id,
        "manifest_path": manifest_path,
        "definition_hash": experiment_identity(manifest),
        "configuration_hash": configuration_identity(configuration),
        "dataset_freezes": sorted({str(v) for v in (manifest.get("dataset_freezes") or [])}),
        "status_at_freeze": manifest.get("status"),
        "frozen_at": frozen_at,
        "repository_revision": repository_revision,
        "repository_dirty": repository_dirty,
        "code_revision_at_freeze": dict(code_revision_at_freeze or {}) or None,
        "frozen_by_command": frozen_by_command,
        "generated_by": GENERATED_BY_DEFAULT,
    }
    payload["freeze_id"] = experiment_freeze_identity(payload)
    return ExperimentFreezeResult(
        freeze=payload,
        output_path=freeze_relative_path(str(experiment_id)),
        written=False,
        unchanged=False,
        errors=errors,
    )


def write_experiment_freeze(
    root: Path | str, result: ExperimentFreezeResult
) -> ExperimentFreezeResult:
    """Write a definition freeze, refusing to replace a different one.

    Idempotent for an unchanged definition; an exception when the identity has moved.
    Silently replacing a freeze is exactly the act this mechanism exists to prevent, so
    the refusal is loud.
    """
    base = Path(root)
    if result.errors:
        return result

    target = base / result.output_path
    target.parent.mkdir(parents=True, exist_ok=True)
    new_text = pretty_json_text(result.freeze)

    if target.exists():
        existing_text = target.read_text(encoding="utf-8")
        existing = load_document(target, kind="experiment_freeze")
        existing_id = (existing.value or {}).get("freeze_id") if existing.is_present else None
        if existing_id == result.freeze.get("freeze_id"):
            return ExperimentFreezeResult(
                freeze=result.freeze,
                output_path=result.output_path,
                written=False,
                unchanged=True,
                byte_identical=existing_text == new_text,
            )
        existing_definition = (existing.value or {}).get("definition_hash")
        raise IntegrityError(
            f"refusing to overwrite the frozen definition at {result.output_path}: it records "
            f"definition_hash={str(existing_definition)[:12]}… "
            f"(freeze_id {str(existing_id)[:12]}…) and the manifest has since changed. A frozen "
            f"definition is immutable; if the experiment genuinely changed, it is a different "
            f"experiment and needs a new id"
        )

    target.write_text(new_text, encoding="utf-8")
    return ExperimentFreezeResult(
        freeze=result.freeze,
        output_path=result.output_path,
        written=True,
        unchanged=False,
    )


def validate_experiment_freeze_document(freeze: Mapping[str, Any], *, origin: str) -> list[str]:
    """Structural validation, without reading the manifest."""
    errors: list[str] = []
    errors.extend(reject_unknown_fields(freeze, TOP_LEVEL_FIELDS, origin=origin))
    errors.extend(require_fields(freeze, REQUIRED_FIELDS, origin=origin))
    if any("required field" in error for error in errors):
        return errors

    errors.extend(
        validate_relative_posix_path(
            freeze.get("manifest_path"), origin=origin, label="manifest_path"
        )
    )
    if not is_identifier(freeze.get("experiment_id")):
        errors.append(
            f"{origin}: experiment_id={freeze.get('experiment_id')!r} is not a valid identifier"
        )
    for field_name in ("definition_hash", "configuration_hash"):
        if not is_sha256(freeze.get(field_name)):
            errors.append(
                f"{origin}: {field_name} must be a sha256 digest, found {freeze.get(field_name)!r}"
            )
    freezes = freeze.get("dataset_freezes")
    if not isinstance(freezes, list):
        errors.append(f"{origin}: dataset_freezes must be a list, found {type(freezes).__name__}")
    else:
        for index, value in enumerate(freezes):
            if not is_sha256(value):
                errors.append(f"{origin}: dataset_freezes[{index}]={value!r} is not a freeze id")

    recorded_id = freeze.get("freeze_id")
    if not is_sha256(recorded_id):
        errors.append(f"{origin}: freeze_id must be a sha256 digest, found {recorded_id!r}")
    else:
        recomputed = experiment_freeze_identity(freeze)
        if recomputed != recorded_id:
            errors.append(
                f"{origin}: freeze_id does not match its own contents: recorded "
                f"{str(recorded_id)[:12]}…, recomputed {recomputed[:12]}…; the frozen definition "
                f"document has been edited"
            )
    errors.extend(require_int(freeze, "freeze_format_version", origin=origin, minimum=1))
    return errors


@dataclass
class DefinitionDrift:
    """What a definition freeze and its manifest now disagree about."""

    experiment_id: str
    path: str
    errors: list[str] = field(default_factory=list)
    compared_fields: int = 0

    @property
    def ok(self) -> bool:
        return not self.errors

    @property
    def drifted(self) -> bool:
        return bool(self.errors)

    def to_dict(self) -> dict[str, Any]:
        return {
            "experiment_id": self.experiment_id,
            "path": self.path,
            "ok": self.ok,
            "compared_fields": self.compared_fields,
            "errors": list(self.errors),
        }


def verify_experiment_freeze(
    root: Path | str, freeze: Mapping[str, Any], *, path: str = ""
) -> DefinitionDrift:
    """Compare a frozen definition against the manifest as it is now.

    Every pinned field is recomputed and compared. ``compared_fields`` is reported so that
    a caller can see *how many* comparisons actually happened: a comparison function that
    silently compared nothing would otherwise return "no drift" and look like success.
    """
    base = Path(root)
    experiment_id = str(freeze.get("experiment_id", "<missing>"))
    result = DefinitionDrift(
        experiment_id=experiment_id, path=path or freeze_relative_path(experiment_id)
    )
    result.errors.extend(validate_experiment_freeze_document(freeze, origin=result.path))
    if result.errors:
        return result

    manifest_path = str(freeze["manifest_path"])
    load = load_document(base / manifest_path, kind="experiment_manifest")
    if load.is_absent:
        result.errors.append(
            f"{result.path}: the manifest this definition freeze pins is missing "
            f"({manifest_path}), so the frozen definition can no longer be compared"
        )
        return result
    if load.is_error:
        result.errors.extend(load.errors(label=f"{result.path} -> {manifest_path}"))
        return result

    manifest = load.require()

    if manifest.get("experiment_id") != experiment_id:
        result.errors.append(
            f"{result.path}: freeze and manifest disagree about experiment_id: freeze records "
            f"{experiment_id!r}, {manifest_path} records {manifest.get('experiment_id')!r}"
        )

    result.compared_fields += 1
    actual_definition = experiment_identity(manifest)
    if actual_definition != freeze.get("definition_hash"):
        result.errors.append(
            f"{result.path}: the experiment definition changed since it was frozen: recorded "
            f"{str(freeze.get('definition_hash'))[:12]}…, {manifest_path} now hashes to "
            f"{actual_definition[:12]}…"
        )

    result.compared_fields += 1
    configuration = manifest.get("configuration")
    actual_configuration = (
        configuration_identity(configuration) if isinstance(configuration, dict) else None
    )
    if actual_configuration != freeze.get("configuration_hash"):
        result.errors.append(
            f"{result.path}: the configuration changed since it was frozen: recorded "
            f"{str(freeze.get('configuration_hash'))[:12]}…, now {str(actual_configuration)[:12]}…"
        )

    result.compared_fields += 1
    actual_freezes = sorted({str(v) for v in (manifest.get("dataset_freezes") or [])})
    if actual_freezes != list(freeze.get("dataset_freezes") or []):
        result.errors.append(
            f"{result.path}: the frozen inputs changed since the definition was frozen: recorded "
            f"{[str(v)[:12] + '…' for v in (freeze.get('dataset_freezes') or [])]}, now "
            f"{[str(v)[:12] + '…' for v in actual_freezes]}"
        )

    result.compared_fields += 1
    if manifest.get("status") != freeze.get("status_at_freeze"):
        result.errors.append(
            f"{result.path}: status changed since the definition was frozen: recorded "
            f"{freeze.get('status_at_freeze')!r}, now {manifest.get('status')!r}. A status "
            f"advance is expected, but it must be recorded as a lifecycle event rather than "
            f"left to be discovered by comparing two files"
        )
    return result


def load_experiment_freeze(
    root: Path | str, relative: str
) -> tuple[dict[str, Any] | None, list[str]]:
    """Load one experiment freeze document."""
    load = load_document(Path(root) / relative, kind="experiment_freeze")
    if load.is_error:
        return None, load.errors()
    if load.is_absent:
        return None, [f"{load.path}: experiment definition freeze is missing"]
    return load.require(), []


